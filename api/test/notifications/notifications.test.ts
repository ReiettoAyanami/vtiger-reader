import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { READ_OPERATIONS } from '../../src/modules/crm/webservice.js';
import { expectProblem, makeApi, type Api } from '../support/api.js';
import { rawRows } from '../support/db.js';
import { FakeCrm } from '../support/fake-crm.js';
import { browserSubscription, FakePush } from '../support/fake-push.js';
import { OTHER, idOf, TESTER } from '../support/session.js';

const MARIO = { username: 'mario.rossi', accessKey: 'AbCdEf0123456789' }; // CRM user 19x5
/** "Now" for these tests: after the CRM's tickets. */
const NOW = new Date('2026-11-04T12:00:00Z');

const pick = (...values: string[]) => ({ name: 'picklist', picklistValues: values.map((value) => ({ value, label: value })) });

/** A CRM with two tickets already there, a group, a contact. */
function companyCrm(): FakeCrm {
  const crm = new FakeCrm();
  crm.modules.set('HelpDesk', {
    name: 'HelpDesk',
    label: 'Ticket',
    idPrefix: '17',
    fields: [
      { name: 'id', label: 'id', type: { name: 'autogenerated' } },
      { name: 'ticket_no', label: 'Ticket n.', type: { name: 'string' } },
      { name: 'ticket_title', label: 'Titolo', type: { name: 'string' } },
      { name: 'ticketstatus', label: 'Stato', type: pick('Open', 'Closed') },
      { name: 'ticketpriorities', label: 'Priorità', type: pick('Low', 'High') },
      { name: 'ticketcategories', label: 'Categoria', type: pick('Hardware', 'Software') },
      { name: 'createdtime', label: 'Creato', type: { name: 'datetime' } },
      { name: 'modifiedtime', label: 'Modificato', type: { name: 'datetime' } },
      { name: 'assigned_user_id', label: 'Assegnato a', type: { name: 'owner' } },
      { name: 'parent_id', label: 'Organizzazione', type: { name: 'reference', refersTo: ['Accounts'] } },
      { name: 'contact_id', label: 'Contatto', type: { name: 'reference', refersTo: ['Contacts'] } },
    ],
  });
  crm.modules.set('Groups', { name: 'Groups', idPrefix: '20', fields: ['groupname', 'id'].map((name) => ({ name, label: name, type: { name: 'string' } })) });
  crm.modules.set('Contacts', { name: 'Contacts', idPrefix: '12', fields: ['firstname', 'lastname', 'id'].map((name) => ({ name, label: name, type: { name: 'string' } })) });
  crm.tables.set('Groups', [{ id: '20x1', groupname: 'Primo livello' }]);
  crm.tables.set('Contacts', [{ id: '12x1', firstname: 'Mario', lastname: 'Bianchi' }]);
  crm.tables.set('HelpDesk', [ticket(1, '2026-11-03 10:00:00'), ticket(2, '2026-11-03 11:00:00', { assigned_user_id: '20x1' })]);
  return crm;
}

function ticket(n: number, createdtime: string, more: Record<string, string> = {}): Record<string, string> {
  return {
    id: `17x${n}`,
    ticket_no: `TK-${String(n).padStart(4, '0')}`,
    ticket_title: `Ticket ${n}`,
    ticketstatus: 'Open',
    ticketpriorities: 'High',
    ticketcategories: 'Hardware',
    createdtime,
    modifiedtime: createdtime,
    assigned_user_id: '19x5',
    parent_id: '',
    contact_id: '12x1',
    ...more,
  };
}

let api: Api;
let crm: FakeCrm;
let push: FakePush;
let lists: Record<string, number>;

/** One round of checks, as the server runs every 2 minutes. */
const check = () => api.app.notifications.checkAll();
const arrive = (...rows: Array<Record<string, string>>) => crm.tables.get('HelpDesk')!.push(...rows);

beforeEach(async () => {
  crm = companyCrm();
  push = new FakePush();
  api = await makeApi({ crm, push, clock: () => new Date(NOW) });
  expect((await api.put('/api/crm/link', { url: crm.url, ...MARIO })).status).toBe(200);
  lists = Object.fromEntries(((await api.get('/api/lists')).body as Array<{ id: number; name: string }>).map((l) => [l.name, l.id]));
});
afterEach(async () => {
  // Read-only: nothing but reading operations ever reached the CRM.
  expect(crm.calls.filter((c) => !(READ_OPERATIONS as readonly string[]).includes(c.operation))).toEqual([]);
  await api.app.close();
});

describe('settings', () => {
  it('on from the start, for "my open tickets" and "unassigned"; no device yet', async () => {
    expect((await api.get('/api/notifications/settings')).body).toEqual({
      enabled: true,
      lists: [lists['My open tickets'], lists['Unassigned']],
      devices: 0,
    });
  });

  it('the user picks the lists and turns them off; another user\'s list is not found', async () => {
    const res = await api.put('/api/notifications/settings', { enabled: false, lists: [lists['All tickets']] });
    expect(res.body).toEqual({ enabled: false, lists: [lists['All tickets']], devices: 0 });
    const theirs = (await api.as(OTHER).get('/api/lists')).body[0].id as number;
    expectProblem(await api.put('/api/notifications/settings', { enabled: true, lists: [theirs] }), 404, 'not-found');
    expect((await api.get('/api/notifications/settings')).body.lists).toEqual([lists['All tickets']]);
  });
});

describe('the checks', () => {
  it('the first only looks: nothing that was already there is sent', async () => {
    await api.put('/api/push/subscription', browserSubscription());
    await check();
    expect(push.sent).toEqual([]);
    expect(await rawRows('SELECT watermark FROM notification_state')).toEqual([{ watermark: new Date('2026-11-03T11:00:00Z') }]);
  });

  it('a new ticket of mine: a push to each browser, its number and title, opening it; once', async () => {
    const phone = browserSubscription();
    const laptop = browserSubscription();
    await api.put('/api/push/subscription', phone);
    await api.put('/api/push/subscription', laptop);
    await check();
    arrive(ticket(3, '2026-11-04 09:00:00', { ticket_title: 'Stampante ferma' }));
    await check();
    expect(push.sent.map((s) => s.endpoint)).toEqual([phone.endpoint, laptop.endpoint]);
    expect(push.sent[0]!.message).toEqual({
      title: 'TK-0003 Stampante ferma',
      body: 'Mario Bianchi · High · Hardware',
      url: '/tester/tickets/17x3',
      tag: `tickets-${await idOf(api.app, TESTER)}`,
    });
    // VAPID: who the push services may write to (an http instance: the administrator's mail).
    expect(push.sent[0]!.subject).toMatch(/^mailto:/);
    await check();
    expect(push.sent).toHaveLength(2);
  });

  it('only the tickets in the lists picked: not a colleague\'s, not a closed one', async () => {
    await api.put('/api/push/subscription', browserSubscription());
    await check();
    arrive(
      ticket(3, '2026-11-04 09:00:00'),
      ticket(4, '2026-11-04 09:01:00', { assigned_user_id: '20x1' }),
      ticket(5, '2026-11-04 09:02:00', { assigned_user_id: '19x9' }),
      ticket(6, '2026-11-04 09:03:00', { ticketstatus: 'Closed' }),
    );
    await check();
    expect(push.sent.map((s) => s.message)).toEqual([
      { title: '2 new tickets', body: 'TK-0004 Ticket 4\nTK-0003 Ticket 3', url: '/tester', tag: expect.stringMatching(/^tickets-/) },
    ]);
  });

  it('turned off: no check; turned on again: from then on, not what came meanwhile', async () => {
    await api.put('/api/push/subscription', browserSubscription());
    await check();
    await api.put('/api/notifications/settings', { enabled: false, lists: [lists['My open tickets']] });
    arrive(ticket(3, '2026-11-04 09:00:00'));
    await check();
    await api.put('/api/notifications/settings', { enabled: true, lists: [lists['My open tickets']] });
    await check();
    expect(push.sent).toEqual([]);
    arrive(ticket(4, '2026-11-04 10:00:00'));
    await check();
    expect(push.sent.map((s) => s.message.title)).toEqual(['TK-0004 Ticket 4']);
  });

  it('no list picked: nothing', async () => {
    await api.put('/api/push/subscription', browserSubscription());
    await api.put('/api/notifications/settings', { enabled: true, lists: [] });
    await check();
    arrive(ticket(3, '2026-11-04 09:00:00'));
    await check();
    expect(push.sent).toEqual([]);
  });

  it('a user without a CRM link, or blocked, is not checked; a CRM down stops nobody else', async () => {
    await api.put('/api/push/subscription', browserSubscription());
    await check();
    arrive(ticket(3, '2026-11-04 09:00:00'));
    await rawRows('UPDATE users SET banned = 1 WHERE username = ?', ['tester']);
    await check();
    expect(push.sent).toEqual([]);
    await rawRows('UPDATE users SET banned = 0');
    crm.down = true;
    await check();
    crm.down = false;
    await check();
    expect(push.sent).toHaveLength(1);
  });

  it('a browser the push service no longer knows goes', async () => {
    const gone = browserSubscription();
    const kept = browserSubscription();
    await api.put('/api/push/subscription', gone);
    await api.put('/api/push/subscription', kept);
    push.gone.add(gone.endpoint);
    await check();
    arrive(ticket(3, '2026-11-04 09:00:00'));
    await check();
    expect((await rawRows('SELECT endpoint FROM push_subscription')).map((r) => r.endpoint)).toEqual([kept.endpoint]);
    expect((await api.get('/api/notifications/settings')).body.devices).toBe(1);
  });

  it('an open page hears of new tickets on its stream', async () => {
    const stream = await api.stream('/api/notifications/stream', 'event: ready');
    expect(stream.status).toBe(200);
    expect(String(stream.headers['content-type'])).toContain('text/event-stream');
    await check();
    arrive(ticket(3, '2026-11-04 09:00:00'));
    await check();
    expect(await stream.more()).toBe('event: tickets\ndata: {"count":1}\n\n');
  });
});

describe('the bell', () => {
  it('the tickets created since it was last opened, newest first; seen, they leave it', async () => {
    expect((await api.get('/api/notifications')).body).toEqual({ enabled: true, items: [] });
    arrive(ticket(3, '2026-11-04 09:00:00'), ticket(4, '2026-11-04 09:30:00', { assigned_user_id: '19x9' }), ticket(5, '2026-11-04 10:00:00'));
    const bell = (await api.get('/api/notifications')).body;
    expect(bell.items.map((t: { id: string; createdAt: string }) => [t.id, t.createdAt])).toEqual([
      ['17x5', '2026-11-04T10:00:00Z'],
      ['17x3', '2026-11-04T09:00:00Z'],
    ]);
    expect((await api.post('/api/notifications/seen', { upTo: '2026-11-04T09:00:00Z' })).status).toBe(204);
    expect((await api.get('/api/notifications')).body.items.map((t: { id: string }) => t.id)).toEqual(['17x5']);
    await api.post('/api/notifications/seen', { upTo: '2026-11-04T10:00:00Z' });
    // An older "seen" does not bring them back.
    await api.post('/api/notifications/seen', { upTo: '2026-11-04T08:00:00Z' });
    expect((await api.get('/api/notifications')).body.items).toEqual([]);
  });

  it('notifications off: an empty bell', async () => {
    await api.put('/api/notifications/settings', { enabled: false, lists: [] });
    expect((await api.get('/api/notifications')).body).toEqual({ enabled: false, items: [] });
  });

  it('"seen" needs an instant with its offset', async () => {
    expectProblem(await api.post('/api/notifications/seen', { upTo: 'yesterday' }), 400, 'validation');
  });
});

describe('browsers', () => {
  it("the instance's own VAPID key, the same every time and after a restart", async () => {
    const key = (await api.get('/api/push/key')).body.publicKey as string;
    expect(Buffer.from(key, 'base64url')).toHaveLength(65);
    expect((await api.get('/api/push/key')).body.publicKey).toBe(key);
    const again = await makeApi({ crm });
    expect((await again.get('/api/push/key')).body.publicKey).toBe(key);
    await again.app.close();
    // The private key is sealed.
    const [row] = await rawRows('SELECT private_key_sealed FROM push_vapid');
    expect(String(row!.private_key_sealed)).toMatch(/^v1\./);
  });

  it('a browser subscribes once (again: the same row), and unsubscribes', async () => {
    const sub = browserSubscription();
    expect((await api.put('/api/push/subscription', sub)).status).toBe(204);
    expect((await api.put('/api/push/subscription', sub)).status).toBe(204);
    expect((await api.get('/api/notifications/settings')).body.devices).toBe(1);
    expect((await api.post('/api/push/test')).body).toEqual({ sent: 1 });
    expect(push.sent[0]!.message).toMatchObject({ title: 'vtiger-reader', url: '/tester' });
    expect((await api.post('/api/push/subscription/delete', { endpoint: sub.endpoint })).status).toBe(204);
    expect((await api.get('/api/notifications/settings')).body.devices).toBe(0);
  });

  it('one browser, one user: whoever subscribes it last gets its notifications', async () => {
    const sub = browserSubscription();
    await api.put('/api/push/subscription', sub);
    await api.as(OTHER).put('/api/push/subscription', sub);
    expect((await api.get('/api/notifications/settings')).body.devices).toBe(0);
    expect((await api.as(OTHER).get('/api/notifications/settings')).body.devices).toBe(1);
    // The other user's browser is not the tester's to remove.
    await api.post('/api/push/subscription/delete', { endpoint: sub.endpoint });
    expect((await api.as(OTHER).get('/api/notifications/settings')).body.devices).toBe(1);
  });

  it('a push service is a public https address; the keys are real ones', async () => {
    const sub = browserSubscription();
    expectProblem(await api.put('/api/push/subscription', { ...sub, endpoint: 'http://push.example.com/x' }), 400, 'validation');
    expectProblem(await api.put('/api/push/subscription', { ...sub, endpoint: 'not an address' }), 400, 'validation');
    expectProblem(await api.put('/api/push/subscription', { ...sub, keys: { ...sub.keys, p256dh: 'AAAA' } }), 400, 'validation');
    expectProblem(await api.put('/api/push/subscription', { ...sub, keys: { ...sub.keys, auth: 'AAAA' } }), 400, 'validation');
    const lan = await makeApi({ crm, hostAllowed: async (host) => host !== '192.168.1.5' });
    expectProblem(await lan.put('/api/push/subscription', { ...sub, endpoint: 'https://192.168.1.5/push' }), 400, 'validation');
    await lan.app.close();
  });
});
