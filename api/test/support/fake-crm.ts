import { createHash } from 'node:crypto';
import type { Fetch } from '../../src/modules/crm/webservice.js';

/**
 * A CRM webservice in memory, answering as vtiger does (OpenCRM manual): getchallenge, login with
 * md5(token + access key), sessions the CRM can close, GET or POST per operation, the
 * `{ success, result | error }` envelope. It records every call, to see what left the server.
 */
export interface FakeCall {
  method: string;
  operation: string;
  params: Record<string, string>;
}

export interface FakeUser {
  accessKey: string;
  /** The CRM's id of the user, e.g. 19x5. */
  id: string;
}

const POST = new Set(['login', 'logout', 'create', 'update', 'revise', 'delete']);

export class FakeCrm {
  readonly url = 'https://crm.example.invalid';
  readonly calls: FakeCall[] = [];
  readonly users = new Map<string, FakeUser>([
    ['mario.rossi', { accessKey: 'AbCdEf0123456789', id: '19x5' }],
    ['anna.bianchi', { accessKey: 'ZyXwVu9876543210', id: '19x7' }],
  ]);
  /** describe answers, per module. */
  readonly modules = new Map<string, unknown>([
    [
      'HelpDesk',
      {
        name: 'HelpDesk',
        label: 'Ticket',
        fields: [
          { name: 'id', label: 'Id', type: { name: 'autogenerated' } },
          { name: 'ticket_no', label: 'Numero ticket', type: { name: 'string' } },
          { name: 'ticket_title', label: 'Titolo', type: { name: 'string' } },
          {
            name: 'ticketstatus',
            label: 'Stato',
            type: { name: 'picklist', picklistValues: [{ value: 'Open', label: 'Aperto' }, { value: 'Closed', label: 'Chiuso' }] },
          },
          { name: 'parent_id', label: 'Organizzazione', type: { name: 'reference', refersTo: ['Accounts'] } },
        ],
      },
    ],
  ]);
  readonly records = new Map<string, Record<string, unknown>>();
  readonly files = new Map<string, { filename: string; filecontents: string }>();
  /** What a query answers (the query's text and the CRM user asking). */
  queryAnswer: (query: string, username: string) => unknown[] = () => [];
  /** No answer at all: a network error. */
  down = false;
  /** Waits before answering files_retrieve (to see how many run at once). */
  fileDelayMs = 0;
  /** files_retrieve running now, and the most at once. */
  filesRunning = 0;
  filesMost = 0;

  private readonly challenges = new Map<string, string>();
  private readonly sessions = new Map<string, string>();
  private counter = 0;

  /** The CRM closes every open session (expiry, a restart). */
  closeSessions(): void {
    this.sessions.clear();
  }

  openSessions(): number {
    return this.sessions.size;
  }

  operations(): string[] {
    return this.calls.map((c) => c.operation);
  }

  readonly fetch: Fetch = async (input, init) => {
    if (this.down) throw new TypeError('fetch failed');
    const url = new URL(String(input));
    const method = init?.method ?? 'GET';
    const params = Object.fromEntries(method === 'POST' ? new URLSearchParams(String(init?.body ?? '')) : url.searchParams);
    const operation = params['operation'] ?? '';
    this.calls.push({ method, operation, params });
    if (url.pathname !== '/webservice.php') return new Response('Not found', { status: 404 });
    if (POST.has(operation) !== (method === 'POST')) return fail('ACCESS_DENIED', 'Permission to perform the operation is denied');
    return this.answer(operation, params);
  };

  private async answer(operation: string, p: Record<string, string>): Promise<Response> {
    if (operation === 'getchallenge') {
      const token = `token-${++this.counter}`;
      this.challenges.set(p['username'] ?? '', token);
      return ok({ token, serverTime: 0, expireTime: 300 });
    }
    if (operation === 'login') {
      const username = p['username'] ?? '';
      const user = this.users.get(username);
      const token = this.challenges.get(username);
      this.challenges.delete(username);
      if (!user || !token || p['accessKey'] !== md5(token + user.accessKey)) {
        return fail('INVALID_USER_CREDENTIALS', 'Invalid username or password');
      }
      const sessionName = `session-${++this.counter}`;
      this.sessions.set(sessionName, username);
      return ok({ sessionName, userId: user.id, version: '0.22', vtigerVersion: '7.5.0' });
    }
    const username = this.sessions.get(p['sessionName'] ?? '');
    if (!username) return fail('INVALID_SESSIONID', 'Session Identifier provided is Invalid');
    switch (operation) {
      case 'logout':
        this.sessions.delete(p['sessionName'] ?? '');
        return ok({ message: 'successfull' });
      case 'listtypes':
        return ok({ types: [...this.modules.keys()], information: {} });
      case 'describe': {
        const module = this.modules.get(p['elementType'] ?? '');
        return module ? ok(module) : fail('ACCESS_DENIED', 'Permission to perform the operation is denied');
      }
      case 'query':
        return ok(this.queryAnswer(p['query'] ?? '', username));
      case 'retrieve': {
        const record = this.records.get(p['id'] ?? '');
        return record ? ok(record) : fail('ACCESS_DENIED', 'Permission to perform the operation is denied for id');
      }
      case 'files_retrieve': {
        this.filesRunning++;
        this.filesMost = Math.max(this.filesMost, this.filesRunning);
        await new Promise((resolve) => setTimeout(resolve, this.fileDelayMs));
        this.filesRunning--;
        const file = this.files.get(p['id'] ?? '');
        return ok(file ? [file] : []);
      }
      default:
        return fail('UNKNOWN_OPERATION', `Unknown operation requested ${operation}`);
    }
  }
}

function md5(text: string): string {
  return createHash('md5').update(text).digest('hex');
}

function ok(result: unknown): Response {
  return Response.json({ success: true, result });
}

function fail(code: string, message: string): Response {
  return Response.json({ success: false, error: { code, message } });
}
