describe('/api/tickets', () => {
  it('my open tickets by default: newest first, names read from the CRM, times in UTC', async () => {
    const res = await api.get('/api/tickets');
    expect(res.status, JSON.stringify(res.body)).toBe(200);
    expect(res.body).toEqual({
      page: 0,
      size: 50,
      total: 1,
      items: [
        {
          id: '17x1',
          number: 'TK-2026-000001',
          title: 'Stampante ferma',
          status: 'Aperto',
          priority: 'Alta',
          category: 'Hardware',
          createdAt: '2026-11-03T10:00:00Z',
          modifiedAt: '2026-11-03T12:00:00Z',
          owner: { kind: 'me' },
          // read later, through /api/names: ~100 ms each on a real CRM
          organization: { id: '11x1', name: null },
          // one query for every contact of the page
          contact: { id: '12x1', name: 'Mario Bianchi' },
          closed: false,
        },
      ],
    });
    expect(crm.calls.filter((c) => c.operation === 'retrieve')).toEqual([]);
  });

  it('/api/names: the names behind ids, those the user may read', async () => {
    expect((await api.get('/api/names?ids=11x1,11x2,11x99')).body).toEqual({ '11x1': 'Acme Srl', '11x2': 'Beta Spa' });
    expectProblem(await api.get(`/api/names?ids=${encodeURIComponent("11x1,x' OR 1")}`), 400);
    expectProblem(await api.get(`/api/names?ids=${Array.from({ length: 101 }, (_, i) => `11x${i + 1}`).join(',')}`), 400);
  });

  it('owners: me, a group by name, a colleague (their names are not readable)', async () => {
    const res = await api.get('/api/tickets?folder=all');
    expect(res.body.items.map((t: { id: string; owner: unknown }) => [t.id, t.owner])).toEqual([
      ['17x2', { kind: 'group', name: 'Primo livello' }],
      ['17x1', { kind: 'me' }],
      ['17x3', { kind: 'me' }],
      ['17x4', { kind: 'colleague' }],
    ]);
    expect(res.body.items.find((t: { id: string }) => t.id === '17x3').closed).toBe(true);
  });

  it('search: words in the title, or a number', async () => {
    expect((await api.get('/api/tickets?folder=all&q=stampante')).body.items.map((t: { id: string }) => t.id)).toEqual(['17x1', '17x3']);
    expect((await api.get('/api/tickets?folder=all&q=TK-2026-000002')).body.items.map((t: { id: string }) => t.id)).toEqual(['17x2']);
    // what the user types cannot break the query
    expect((await api.get(`/api/tickets?folder=all&q=${encodeURIComponent("x' OR '1'='1")}`)).body.total).toBe(0);
  });

  it('filters: status, contact, organization; sort and pages', async () => {
    expect((await api.get('/api/tickets?folder=all&status=Closed')).body.items.map((t: { id: string }) => t.id)).toEqual(['17x3']);
    expect((await api.get('/api/tickets?folder=all&contact=12x2')).body.items.map((t: { id: string }) => t.id)).toEqual(['17x2']);
    expect((await api.get('/api/tickets?folder=all&organization=11x2')).body.total).toBe(2);
    const page = await api.get('/api/tickets?folder=all&sort=modified&dir=asc&size=2&page=1');
    expect(page.body).toMatchObject({ page: 1, size: 2, total: 4 });
    expect(page.body.items.map((t: { id: string }) => t.id)).toEqual(['17x2', '17x1']);
  });

  it('folders by group, category and support group', async () => {
    expect((await api.get('/api/tickets?folder=group:20x1')).body.items.map((t: { id: string }) => t.id)).toEqual(['17x2']);
    expect((await api.get(`/api/tickets?folder=${encodeURIComponent('pick:ticketcategories:Software')}`)).body.total).toBe(0);
    expect((await api.get(`/api/tickets?folder=${encodeURIComponent('pick:gruppo_di_supporto:Alpha')}`)).body.total).toBe(2);
  });

  it('refuses a folder, status or id that is not the CRM’s', async () => {
    expectProblem(await api.get('/api/tickets?folder=nope'), 400);
    expectProblem(await api.get('/api/tickets?folder=group:20x99'), 400);
    expectProblem(await api.get(`/api/tickets?folder=${encodeURIComponent("pick:ticketstatus:Open")}`), 400);
    expectProblem(await api.get('/api/tickets?status=Gone'), 400);
    expectProblem(await api.get(`/api/tickets?contact=${encodeURIComponent("12x1' OR 1")}`), 400);
    expectProblem(await api.get('/api/tickets?size=500'), 400);
  });
});

describe('/api/tickets/:id', () => {
  it('a ticket: header, the description cleaned with its HTML, the solution, fields, comments in order, documents', async () => {
    const res = await api.get('/api/tickets/17x1');
    expect(res.status, JSON.stringify(res.body)).toBe(200);
    const t = res.body;
    expect(t).toMatchObject({
      id: '17x1',
      number: 'TK-2026-000001',
      status: 'Aperto',
      owner: { kind: 'me' },
      organization: { id: '11x1', name: 'Acme Srl' },
      contact: { id: '12x1', name: 'Mario Bianchi' },
    });
    expect(t.crmLink).toBe(`${crm.url}/index.php?module=HelpDesk&view=Detail&record=1`);
    expect(t.description).toEqual({ text: 'La stampante non stampa.', cut: true, html: '<p>La stampante non stampa.</p><p>Mario Bianchi<br>Tel. 0541 123456</p>' });
    expect(t.solution).toBeNull();
    expect(t.fields).toEqual([
      { name: 'gruppo_di_supporto', label: 'Gruppo di supporto', value: 'Alpha' },
      { name: 'contratto', label: 'Contratto', value: 'Contratto 2026' },
      { name: 'from_portal', label: 'Dal portale', value: 'Yes' },
    ]);
    expect(t.comments.map((c: { id: string; author: unknown; private: boolean; sameAsDescription: boolean; files: string[]; at: string }) => [c.id, c.author, c.private, c.sameAsDescription, c.files, c.at])).toEqual([
      ['30x1', { kind: 'customer', id: '12x1', name: 'Mario Bianchi' }, false, true, ['15x1', '15x2'], '2026-11-03T10:00:01Z'],
      ['30x2', { kind: 'colleague' }, false, false, ['15x3'], '2026-11-03T10:30:00Z'],
      ['30x3', { kind: 'me' }, true, false, [], '2026-11-03T11:00:00Z'],
    ]);
    expect(t.comments[1].body).toEqual({ text: 'Ci guardo io.', cut: false });
    expect(t.documents).toEqual([{ id: '7x1', title: 'Log', fileName: 'log.pdf', files: ['15x9'] }]);
  });

  it('a closed ticket has its solution', async () => {
    expect((await api.get('/api/tickets/17x3')).body.solution).toEqual({ text: 'Inviata.', cut: false, html: '<p>Inviata.</p>' });
  });

  it('an id that is not a ticket, or that the CRM does not give: 404', async () => {
    expectProblem(await api.get('/api/tickets/11x1'), 404, 'not-found');
    expectProblem(await api.get('/api/tickets/17x999'), 404, 'not-found');
    expectProblem(await api.get('/api/tickets/abc'), 400);
  });
});

describe('attachments', () => {
  it('measured from their bytes: the logo set aside by the rule, the photo shown, the rest only downloaded', async () => {
    const res = await api.get('/api/tickets/17x1/attachments');
    expect(res.status, JSON.stringify(res.body)).toBe(200);
    const byId = Object.fromEntries((res.body as Array<{ id: string }>).map((a) => [a.id, a]));
    expect(byId['15x1']).toMatchObject({ name: 'image001.png', type: 'image/png', inline: true, width: 300, height: 100, signature: true, mark: null, from: { kind: 'comment', id: '30x1' } });
    expect(byId['15x2']).toMatchObject({ type: 'image/jpeg', width: 800, height: 600, signature: false });
    expect(byId['15x3']).toMatchObject({ name: 'page.png', type: 'application/octet-stream', inline: false, signature: false });
    expect(byId['15x9']).toMatchObject({ type: 'application/pdf', inline: true, from: { kind: 'document', id: '7x1' } });
  });

  it('a file: images and PDFs inline with a policy that runs nothing; anything else downloaded', async () => {
    const png = await api.get('/api/tickets/17x1/files/15x1');
    expect(png.status).toBe(200);
    expect(png.headers['content-type']).toBe('image/png');
    expect(png.headers['content-disposition']).toBe(`inline; filename="image001.png"; filename*=UTF-8''image001.png`);
    expect(png.headers['content-security-policy']).toContain("default-src 'none'");
    expect(png.headers['cache-control']).toBe('private, max-age=3600');
    expect(png.headers['x-content-type-options']).toBe('nosniff');
    const html = await api.get('/api/tickets/17x1/files/15x3');
    expect(html.headers['content-type']).toBe('application/octet-stream');
    expect(String(html.headers['content-disposition'])).toMatch(/^attachment;/);
    expect(String((await api.get('/api/tickets/17x1/files/15x1?download=true')).headers['content-disposition'])).toMatch(/^attachment;/);
  });

  it("only the ticket's own files", async () => {
    expectProblem(await api.get('/api/tickets/17x1/files/15x77'), 404, 'not-found');
    expectProblem(await api.get('/api/tickets/17x2/files/15x1'), 404, 'not-found');
  });

  it('marks: the user says logo or photo, the mark follows the image; taken back, the rule again', async () => {
    expect((await api.put('/api/tickets/17x1/files/15x1/mark', { mark: 'photo' })).body).toEqual({ mark: 'photo' });
    let byId = Object.fromEntries(((await api.get('/api/tickets/17x1/attachments')).body as Array<{ id: string }>).map((a) => [a.id, a]));
    expect(byId['15x1']).toMatchObject({ mark: 'photo', signature: false });
    expect(await rawRows('SELECT mark, CHAR_LENGTH(exact_hash) AS exact, CHAR_LENGTH(dhash) AS dhash FROM image_mark')).toEqual([{ mark: 'photo', exact: 64, dhash: 16 }]);

    expect((await api.put('/api/tickets/17x1/files/15x2/mark', { mark: 'logo' })).body).toEqual({ mark: 'logo' });
    byId = Object.fromEntries(((await api.get('/api/tickets/17x1/attachments')).body as Array<{ id: string }>).map((a) => [a.id, a]));
    expect(byId['15x2']).toMatchObject({ mark: 'logo', signature: true });

    await api.put('/api/tickets/17x1/files/15x1/mark', { mark: null });
    byId = Object.fromEntries(((await api.get('/api/tickets/17x1/attachments')).body as Array<{ id: string }>).map((a) => [a.id, a]));
    expect(byId['15x1']).toMatchObject({ mark: null, signature: true });
    expect(await rawRows('SELECT mark FROM image_mark')).toEqual([{ mark: 'logo' }]);

    expectProblem(await api.put('/api/tickets/17x1/files/15x3/mark', { mark: 'logo' }), 400);
    expectProblem(await api.put('/api/tickets/17x1/files/15x1/mark', { mark: 'banner' }), 400);
  });
});

